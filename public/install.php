<?php

declare(strict_types=1);

/*
 | DEVSPACE web installer. Locks itself after a successful install
 | (storage/installed.lock). Delete this file afterwards for extra safety.
 */

require dirname(__DIR__) . '/app/bootstrap.php';

use App\Core\Database;
use App\Core\HttpException;
use App\Services\Crypto;
use App\Services\Migrator;
use App\Services\UserService;

header('X-Frame-Options: DENY');
header('X-Content-Type-Options: nosniff');
header('Cache-Control: no-store');

if (is_file(storage_path('installed.lock'))) {
    http_response_code(403);
    $message = 'DEVSPACE is already installed. Delete storage/installed.lock to run the installer again.';
    require BASE_PATH . '/views/pages/error.php';
    exit;
}

session_name('devspace_install');
session_start();
$_SESSION['install_csrf'] ??= bin2hex(random_bytes(32));

$requirements = [
    'PHP 8.2+' => PHP_VERSION_ID >= 80200,
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'Sodium extension (vault encryption)' => extension_loaded('sodium'),
    'cURL extension (monitoring)' => extension_loaded('curl'),
    'OpenSSL extension' => extension_loaded('openssl'),
    'mbstring extension' => extension_loaded('mbstring'),
    'zlib extension (backups)' => extension_loaded('zlib'),
    'Project root writable (.env)' => is_writable(BASE_PATH) || is_writable(BASE_PATH . '/.env'),
    'storage/ writable' => is_writable(storage_path()),
    'Frontend build present (public/app)' => is_file(BASE_PATH . '/public/app/index.html'),
];
$requirementsOk = !in_array(false, $requirements, true);

$errors = [];
$old = [
    'db_host' => 'localhost', 'db_port' => '3306', 'db_name' => '', 'db_user' => '',
    'app_url' => (($_SERVER['HTTPS'] ?? '') === 'on' ? 'https://' : 'http://') . ($_SERVER['HTTP_HOST'] ?? 'localhost') . base_path_url(),
    'timezone' => 'Asia/Tashkent', 'name' => '', 'email' => '', 'demo' => '',
];
$success = false;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $old = array_merge($old, array_map(static fn ($v) => is_string($v) ? trim($v) : '', $_POST));
    if (!hash_equals($_SESSION['install_csrf'], (string) ($_POST['_token'] ?? ''))) {
        $errors[] = 'Invalid form token. Reload the page and try again.';
    }
    if (!$requirementsOk) {
        $errors[] = 'Fix the failing requirements first.';
    }
    if (!in_array($old['timezone'], timezone_identifiers_list(), true)) {
        $errors[] = 'Choose a valid timezone.';
    }
    if (!filter_var($old['email'], FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'Enter a valid admin email.';
    }
    $password = (string) ($_POST['password'] ?? '');
    if (mb_strlen($password) < 10 || !preg_match('/[A-Za-z]/', $password) || !preg_match('/\d/', $password)) {
        $errors[] = 'Admin password must be at least 10 characters with letters and numbers.';
    }
    if ($password !== ($_POST['password_confirmation'] ?? '')) {
        $errors[] = 'Passwords do not match.';
    }

    if ($errors === []) {
        try {
            $pdo = new PDO(
                sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $old['db_host'], (int) $old['db_port'], $old['db_name']),
                $old['db_user'],
                (string) ($_POST['db_pass'] ?? ''),
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC, PDO::ATTR_EMULATE_PREPARES => false]
            );
            date_default_timezone_set($old['timezone']);
            $pdo->exec("SET time_zone = '" . date('P') . "'");
            Database::setConnection($pdo);

            $quote = static fn (string $v) => '"' . str_replace(['\\', '"', "\n", "\r"], ['\\\\', '\"', '', ''], $v) . '"';
            $env = implode("\n", [
                '# DEVSPACE configuration — generated by the installer on ' . date('c'),
                '# Never commit this file.',
                'APP_NAME=DEVSPACE',
                'APP_ENV=production',
                'APP_DEBUG=false',
                'APP_URL=' . $quote(rtrim($old['app_url'], '/')),
                'APP_TIMEZONE=' . $old['timezone'],
                'APP_KEY=' . Crypto::generateKey(),
                '',
                'DB_HOST=' . $quote($old['db_host']),
                'DB_PORT=' . (int) $old['db_port'],
                'DB_DATABASE=' . $quote($old['db_name']),
                'DB_USERNAME=' . $quote($old['db_user']),
                'DB_PASSWORD=' . $quote((string) ($_POST['db_pass'] ?? '')),
                '',
                'SESSION_SECURE=auto',
                'SESSION_LIFETIME=480',
                'MAIL_FROM=',
                'BACKUP_DAILY=false',
                '',
            ]);

            Migrator::run($pdo);
            $userId = UserService::create($old['name'], $old['email'], $password, 'admin');

            if (file_put_contents(BASE_PATH . '/.env', $env) === false) {
                throw new RuntimeException('Could not write .env — check permissions.');
            }
            @chmod(BASE_PATH . '/.env', 0640);
            App\Core\Env::load(BASE_PATH . '/.env');

            if (!empty($_POST['demo'])) {
                require BASE_PATH . '/database/seeds/DemoSeeder.php';
                DemoSeeder::run($userId);
            }
            file_put_contents(storage_path('installed.lock'), date('c'));
            $success = true;
            session_destroy();
        } catch (HttpException $e) {
            $errors = array_merge($errors, array_values($e->fields) ?: [$e->getMessage()]);
        } catch (PDOException $e) {
            $errors[] = 'Database error: ' . $e->getMessage();
        } catch (Throwable $e) {
            $errors[] = $e->getMessage();
        }
    }
}

require BASE_PATH . '/views/pages/install.php';
