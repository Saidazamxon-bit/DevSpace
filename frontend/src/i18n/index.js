// Minimal i18n: English source strings are the keys; Uzbek (default) translations live in uz.js.
// Switching language stores the choice and reloads the app.
import uz from './uz';
import { translateServer } from './server';

const KEY = 'ds.lang';
const read = () => { try { return localStorage.getItem(KEY); } catch { return null; } };
export const LANGS = [{ value: 'uz', label: "O'zbekcha" }, { value: 'en', label: 'English' }];
export let lang = read() === 'en' ? 'en' : 'uz';
document.documentElement.lang = lang;

export function setLang(next) {
  try { localStorage.setItem(KEY, next); } catch { /* ignore */ }
  window.location.reload();
}

const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : s);

/** Translate a UI string. `vars` fills {placeholders}. */
export function t(key, vars) {
  const s = lang === 'uz' && uz[key] !== undefined ? uz[key] : key;
  return fill(s, vars);
}

/** Translate text generated by the backend (activity log, notifications, errors). */
export function tr(text) {
  if (lang !== 'uz' || !text) return text;
  return translateServer(String(text));
}
